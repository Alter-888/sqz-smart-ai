-- =============================================
-- 移除管理员侧边栏中的"用户端页面"目录
-- 这些菜单仅供普通用户使用，管理员不需要
-- menu_id: 2040(用户端页面目录), 2041(商品中心),
--          2042(我的订单), 2043(我的工单),
--          2044(AI对话), 2045(我的通知)
-- =============================================

-- 从管理员角色(role_id=1)中移除用户端页面菜单
DELETE FROM sys_role_menu
WHERE role_id = 1
  AND menu_id IN (
    SELECT menu_id FROM sys_menu
    WHERE menu_id = 2040 OR parent_id = 2040
  );
